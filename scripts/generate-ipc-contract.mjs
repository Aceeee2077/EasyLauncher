#!/usr/bin/env node
// Generates the command/argument manifest used to keep the hand-written
// TypeScript IPC contract in sync with the Rust command definitions.
//
// Run with --check to verify the committed file is current without writing.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const rustRoot = "src-tauri/src";
const output = "src/services/ipc.generated.ts";
const check = process.argv.includes("--check");

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return walk(path);
    return path.endsWith(".rs") ? [path] : [];
  });
}

function camelCase(name) {
  return name.replace(/_([a-z0-9])/g, (_, letter) => letter.toUpperCase());
}

function splitParameters(text) {
  const parts = [];
  let depth = 0;
  let current = "";
  for (const char of text) {
    if (char === "<" || char === "(" || char === "[") depth += 1;
    if (char === ">" || char === ")" || char === "]") depth -= 1;
    if (char === "," && depth === 0) {
      parts.push(current);
      current = "";
      continue;
    }
    current += char;
  }
  if (current.trim()) parts.push(current);
  return parts;
}

function collectCommands() {
  const commands = new Map();
  const marker = "#[tauri::command]";
  for (const file of walk(rustRoot)) {
    const source = readFileSync(file, "utf8");
    let index = 0;
    while ((index = source.indexOf(marker, index)) >= 0) {
      const after = source.slice(index + marker.length);
      const signature = after.match(/^\s*pub\s+(?:async\s+)?fn\s+(\w+)\s*\(/);
      if (!signature) {
        index += marker.length;
        continue;
      }
      const name = signature[1];
      let cursor = index + marker.length + signature[0].length;
      let depth = 1;
      let params = "";
      while (cursor < source.length && depth > 0) {
        const char = source[cursor];
        if (char === "(") depth += 1;
        if (char === ")") depth -= 1;
        if (depth > 0) params += char;
        cursor += 1;
      }
      if (depth !== 0) {
        throw new Error(`unbalanced parameter list for ${name} in ${file}`);
      }
      const args = [];
      for (const part of splitParameters(params)) {
        const match = part.trim().match(/^(\w+)\s*:\s*([\s\S]+)$/);
        if (!match) {
          throw new Error(`could not parse parameter "${part.trim()}" of ${name}`);
        }
        const [, param, type] = match;
        if (/\b(?:Managed|Remote|State|AppHandle|WebviewWindow|Window)\b/.test(type)) {
          continue;
        }
        args.push(camelCase(param));
      }
      if (commands.has(name)) {
        throw new Error(`duplicate command definition: ${name}`);
      }
      commands.set(name, args);
      index = cursor;
    }
  }
  return commands;
}

const lib = readFileSync(join(rustRoot, "lib.rs"), "utf8");
const handler = lib.match(/tauri::generate_handler!\[([\s\S]*?)\]/);
if (!handler) throw new Error("could not find tauri::generate_handler! in lib.rs");
const registered = handler[1]
  .split(",")
  .map((entry) => entry.trim())
  .filter(Boolean)
  .map((entry) => entry.split("::").pop());

const commands = collectCommands();
const missing = registered.filter((name) => !commands.has(name));
const unregistered = [...commands.keys()].filter((name) => !registered.includes(name));
if (missing.length) {
  throw new Error(`registered commands with no definition: ${missing.join(", ")}`);
}
if (unregistered.length) {
  throw new Error(
    `#[tauri::command] definitions missing from generate_handler!: ${unregistered.join(", ")}`,
  );
}

const lines = [
  "// Generated by scripts/generate-ipc-contract.mjs — do not edit by hand.",
  "// Run `npm run generate:ipc` after adding or renaming a Tauri command.",
  "",
  "export const ipcCommands = {",
];
for (const name of [...registered].sort()) {
  const args = commands.get(name).map((arg) => JSON.stringify(arg)).join(", ");
  lines.push(`  ${name}: [${args}],`);
}
lines.push("} as const;", "");
lines.push("export type IpcCommand = keyof typeof ipcCommands;");
lines.push("export type IpcArgName<K extends IpcCommand> =");
lines.push("  (typeof ipcCommands)[K][number];", "");

const content = lines.join("\n");
if (check) {
  let current = "";
  try {
    current = readFileSync(output, "utf8");
  } catch {
    // Missing file is a drift failure too.
  }
  if (current !== content) {
    console.error(
      `IPC contract is stale. Run \`npm run generate:ipc\` and commit ${output}.`,
    );
    process.exit(1);
  }
  console.log(`IPC contract is current: ${registered.length} commands.`);
} else {
  writeFileSync(output, content);
  console.log(`Generated ${output} with ${registered.length} commands.`);
}
